import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { v7 as uuidv7 } from "uuid";
import type { DataSource } from "typeorm";
import type { ObjectStorage } from "../../storage/object-storage";
import { KnowledgeApplicationService } from "./knowledge.application.service";
import { KnowledgeQueryService } from "./knowledge.query.service";
import { KnowledgeAuthorizationService } from "./knowledge.scope";
import { KnowledgeFoldersService } from "./knowledge.folders.service";
import { KnowledgeFilesService } from "./knowledge.files.service";
import { KnowledgePreviewJobs } from "./knowledge.preview.service";
import { KnowledgeImportService } from "./knowledge.import.service";
import { createKnowledgeDocxFixture } from "./knowledge.test-documents";
import type { KnowledgeActor } from "./knowledge.types";

export async function validateKnowledgeFolders(ds:DataSource,app:KnowledgeApplicationService,query:KnowledgeQueryService,storage:ObjectStorage,originalAdmin:KnowledgeActor,originalViewer:KnowledgeActor,check:(s:string)=>void) {
  assert(String(ds.options.database).startsWith("knowledge_test_"));
  const admin={...originalAdmin,tenantId:"KNOWLEDGE_FOLDER_TEST"},viewer={...originalViewer,tenantId:admin.tenantId};
  const folders=new KnowledgeFoldersService(app,new KnowledgeAuthorizationService(ds));
  const space=await app.createSpace({name:"文件夹验收人力资源"},admin),other=await app.createSpace({name:"文件夹验收其他空间"},admin);
  for(const id of [space.id,other.id]) await app.setAccess("space",id,{expectedVersion:1,entries:[{subjectType:"ALL",subjectId:null,accessLevel:"VIEWER"}]},admin);
  const create=(name:string,parentFolderId?:string,spaceId=space.id)=>folders.create({spaceId,parentFolderId:parentFolderId??null,name},admin);
  const a=await create("公司制度"),b=await create("人事制度",a.id),c=await create("员工考勤",b.id),empty=await create("空文件夹",c.id);
  assert.equal((await query.list({spaceId:space.id,mode:"working"},admin)).total,0);
  assert.deepEqual((await folders.list(space.id,{selectedId:c.id},viewer)).rows[0].breadcrumb.map(x=>x.title),["文件夹验收人力资源","公司制度","人事制度","员工考勤"]);
  assert.equal((await folders.list(space.id,{parentFolderId:c.id,selectable:"true"},admin)).rows[0].id,empty.id);
  check("independent three-level folders and empty destinations exist immediately without knowledge drafts or publication");
  await assert.rejects(()=>folders.create({spaceId:space.id,name:"员工不得新建"},viewer));
  await assert.rejects(()=>folders.update(a.id,{name:"越权",expectedVersion:1},viewer));
  await assert.rejects(()=>folders.delete(empty.id,{expectedVersion:1},viewer));
  assert(!(await folders.list(space.id,{},viewer)).rows.some(r=>"pageCount" in r||"content" in r));
  check("Space VIEWER may browse folder metadata but cannot create/rename/delete; no hidden page counts or content leak");
  const races=await Promise.allSettled([create("并发同名",a.id),create("并发同名",a.id)]);
  assert.equal(races.filter(r=>r.status==="fulfilled").length,1);assert.equal(races.filter(r=>r.status==="rejected").length,1);
  await create("人事制度");
  check("same-parent name uniqueness is database-enforced under concurrent application commands; different parents permit same names");
  await assert.rejects(()=>folders.update(a.id,{parentFolderId:c.id,expectedVersion:1},admin),/后代/);
  await assert.rejects(()=>folders.update(a.id,{parentFolderId:a.id,expectedVersion:1},admin),/自己/);
  await assert.rejects(()=>ds.query("UPDATE knowledge_folders SET parent_folder_id=$2 WHERE id=$1",[a.id,c.id]));
  check("self/descendant folder cycles rejected by application and database trigger, with no arbitrary depth limit");
  await assert.rejects(()=>folders.delete(a.id,{expectedVersion:1},admin),/子目录/);
  await assert.rejects(()=>app.createPage({spaceId:other.id,folderId:c.id,title:"错误空间关联"},admin),/不属于/);
  await assert.rejects(()=>create("错误子目录",c.id,other.id));
  check("nonempty folder deletion and cross-Space folder IDs rejected transactionally");
  const article=await app.createPage({spaceId:space.id,folderId:c.id,title:"在线考勤制度"},admin);
  assert.equal((await query.detail(article.id,{mode:"working"},admin)).folderId,c.id);
  assert.equal((await query.tree(space.id,{folderId:c.id},viewer)).total,0);
  let pub=await app.publish(article.id,{expectedVersion:1},admin);
  assert.equal((await query.tree(space.id,{folderId:c.id},viewer)).rows[0].id,article.id);
  check("online creation targets explicit folderId; folders require no publish while drafts remain absent from employee lists");
  await folders.update(a.id,{name:"公司制度新版",expectedVersion:1},admin);
  assert.equal((await query.detail(article.id,{},viewer)).breadcrumb![1].title,"公司制度新版");
  assert.equal((await query.list({search:"公司制度新版"},viewer)).rows[0].id,article.id);
  assert.equal((await query.detail(article.id,{versionId:pub.publishedVersionId},viewer)).breadcrumb![1].title,"公司制度");
  await assert.rejects(()=>folders.update(a.id,{name:"过期修改",expectedVersion:1},admin));
  check("folder rename updates current reader/search paths while version breadcrumbs remain immutable; optimistic stale write rejected");
  const destination=await create("培训资料");
  await folders.update(b.id,{parentFolderId:destination.id,expectedVersion:1},admin);
  assert.equal((await query.detail(article.id,{},viewer)).breadcrumb![1].title,"培训资料");
  assert.equal((await folders.list(space.id,{selectedId:c.id},admin)).rows[0].breadcrumb.length,4);
  check("folder move retains descendants and updates complete paths without moving files or mutating snapshots");
  const moved=await app.move(article.id,{spaceId:space.id,folderId:empty.id,parentId:null,expectedVersion:pub.version},admin);
  assert.equal((await query.detail(article.id,{},viewer)).folderId,c.id);
  assert.equal((await query.detail(article.id,{mode:"working"},admin)).folderId,empty.id);
  assert.equal((await query.detail(article.id,{mode:"working"},admin)).hasUnpublishedChanges,true);
  assert.equal((await query.tree(space.id,{folderId:empty.id},viewer)).total,0);
  pub=await app.publish(article.id,{expectedVersion:moved.version},admin);
  assert.equal((await query.detail(article.id,{},viewer)).folderId,empty.id);
  check("unpublished page movement cannot leak draft folderId, search or tree position; publication changes the employee destination");
  const privatePage=await app.createPage({spaceId:space.id,folderId:empty.id,title:"受限知识"},admin);
  await app.setAccess("page",privatePage.id,{expectedVersion:1,restricted:true,entries:[{subjectType:"USER",subjectId:admin.userId,accessLevel:"FULL_ACCESS"}]},admin);
  await app.publish(privatePage.id,{expectedVersion:2},admin);
  assert(!(await query.tree(space.id,{folderId:empty.id},viewer)).rows.some((r:{id:string})=>r.id===privatePage.id));
  assert.equal((await query.list({search:"受限知识"},viewer)).total,0);
  check("existing Page ACL continues to protect files/online content in folders; folder metadata never reveals restricted row counts");
  for (const mode of ["published", "working"] as const) {
    assert.equal((await query.tree(space.id,{mode,legacyOnly:true},admin)).total,0);
  }
  assert.equal((await query.tree(space.id,{legacyOnly:"true"},viewer)).total,0);
  check("legacyOnly root SQL executes in published/working modes with no historical children and returns no false directory entries");
  const legacy=await app.createPage({spaceId:space.id,title:"历史父页面"},admin);await app.publish(legacy.id,{expectedVersion:1},admin);
  const child=await app.createPage({spaceId:space.id,parentId:legacy.id,title:"历史子知识"},admin);
  assert.equal((await query.tree(space.id,{mode:"published",legacyOnly:true},admin)).total,0);
  const workingLegacy=await query.tree(space.id,{mode:"working",legacyOnly:true},admin);
  assert.equal(workingLegacy.total,1);assert.equal(workingLegacy.rows[0].id,legacy.id);
  assert.equal(workingLegacy.rows[0].hasChildren,true);
  check("draft-only historical children appear in working legacy tree but never leak into published legacy tree");
  const cp=await app.publish(child.id,{expectedVersion:1},admin);
  for (const mode of ["published", "working"] as const) {
    const result=await query.tree(space.id,{mode,legacyOnly:true},admin);
    assert.equal(result.total,1);assert.equal(result.rows[0].id,legacy.id);assert.equal(result.rows[0].hasChildren,true);
    const branch=await query.tree(space.id,{mode,legacyOnly:true,parentId:legacy.id},admin);
    assert.equal(branch.total,1);assert.equal(branch.rows[0].id,child.id);
  }
  check("complete legacyOnly count/list/hasChildren SQL executes for published and working historical roots and child branches");
  const privateChild=await app.createPage({spaceId:space.id,parentId:privatePage.id,title:"私密历史子知识"},admin);
  await app.publish(privateChild.id,{expectedVersion:1},admin);
  const employeeLegacy=await query.tree(space.id,{legacyOnly:true},viewer);
  assert.equal(employeeLegacy.total,1);assert.equal(employeeLegacy.rows[0].id,legacy.id);
  assert.equal((await query.tree(space.id,{mode:"published",legacyOnly:true},admin)).total,2);
  assert.equal((await query.tree(space.id,{legacyOnly:true,parentId:privatePage.id},viewer)).total,0);
  await assert.rejects(()=>query.tree(space.id,{mode:"working",legacyOnly:true},viewer),/权限/);
  assert.equal((await query.tree(space.id,{mode:"working",legacyOnly:true},{...viewer,permissions:[...viewer.permissions,"knowledge-pages:*:update"]})).total,0);
  check("legacyOnly keeps ancestor Page ACL: private parents/children and their counts stay hidden; read-only working access rejected");
  const scopedViewer:KnowledgeActor={...viewer,tableDataScopes:[
    {resource:"knowledge-spaces",scope:"ALL",actions:["read"]},
    {resource:"knowledge-pages",scope:"CUSTOM",actions:["read"],rules:[{fieldKey:"title",operator:"CONTAINS",value:"历史"}]}
  ]};
  const scopedResult=await query.tree(space.id,{legacyOnly:true},scopedViewer);
  assert.equal(scopedResult.total,1);assert.equal(scopedResult.rows[0].id,legacy.id);
  assert.equal((await query.tree(space.id,{legacyOnly:true},{...scopedViewer,tenantId:"OTHER_LEGACY_TENANT"})).total,0);
  check("legacyOnly executes ancestor_published field data scopes and retains tenant isolation in real PostgreSQL");

  const legacyMove=await app.move(child.id,{spaceId:space.id,folderId:c.id,parentId:null,expectedVersion:cp.version},admin);
  assert.equal((await query.detail(child.id,{},viewer)).parentId,legacy.id);
  assert.equal((await query.detail(child.id,{},viewer)).breadcrumb![1].title,"历史父页面");
  assert.equal((await query.tree(space.id,{parentId:legacy.id},viewer)).total,1);
  await app.publish(child.id,{expectedVersion:legacyMove.version},admin);
  assert.equal((await query.detail(child.id,{versionId:cp.publishedVersionId},viewer)).parentId,legacy.id);
  check("legacy parentId/link/content/history preserved; explicitly moving a legacy child retains its old published parent until publish");
  let deep=c.id;
  for(let i=0;i<35;i++)deep=(await create("深层"+i,deep)).id;
  assert.equal((await folders.list(space.id,{selectedId:deep},admin)).rows[0].breadcrumb.length,39);
  for(let i=0;i<105;i++)await create("大量目录"+String(i).padStart(3,"0"),deep);
  const first=await folders.list(space.id,{parentFolderId:deep,pageSize:100},viewer),second=await folders.list(space.id,{parentFolderId:deep,pageSize:100,page:2},viewer);
  assert.equal(first.total,105);assert.equal(first.rows.length,100);assert.equal(second.rows.length,5);
  assert.equal((await folders.list(space.id,{search:"大量目录104",selectable:"true"},admin)).rows[0].breadcrumb.length,40);
  assert(!(await folders.list(space.id,{excludeId:destination.id,search:"员工考勤"},admin)).rows.length);
  check("39-node ancestry, 105 sibling lazy pages, complete search paths and descendant exclusions work without first-100 truncation");
  const oldParent=await app.createPage({spaceId:space.id,title:"旧权限父页面"},admin);
  await app.setAccess("page",oldParent.id,{expectedVersion:1,restricted:true,entries:[{subjectType:"USER",subjectId:admin.userId,accessLevel:"FULL_ACCESS"}]},admin);
  const parentPub=await app.publish(oldParent.id,{expectedVersion:2},admin);
  const oldChild=await app.createPage({spaceId:space.id,parentId:oldParent.id,title:"旧权限子页面"},admin);
  await app.publish(oldChild.id,{expectedVersion:1},admin);
  const parentMove=await app.move(oldParent.id,{spaceId:other.id,parentId:null,folderId:null,expectedVersion:parentPub.version},admin);
  await app.publish(oldParent.id,{expectedVersion:parentMove.version},admin);
  await assert.rejects(()=>query.detail(oldChild.id,{},viewer));
  const childWorking=await query.detail(oldChild.id,{mode:"working"},admin);
  await app.move(oldChild.id,{spaceId:space.id,parentId:null,folderId:null,expectedVersion:childWorking.version},admin);
  const parentWorking=await query.detail(oldParent.id,{mode:"working"},admin);
  const parentTrash=await app.transition(oldParent.id,"trash",{expectedVersion:parentWorking.version},admin);
  await assert.rejects(()=>app.purge(oldParent.id,{expectedVersion:parentTrash.version},admin),/历史子页面/);
  await app.transition(oldParent.id,"restore",{expectedVersion:parentTrash.version},admin);
  await assert.rejects(()=>query.detail(oldChild.id,{},viewer));

  // Working parents can be acyclic while independently published parent heads would cycle.
  const cycleA=await app.createPage({spaceId:space.id,title:"历史循环A"},admin);
  const pa=await app.publish(cycleA.id,{expectedVersion:1},admin);
  const cycleB=await app.createPage({spaceId:space.id,parentId:cycleA.id,title:"历史循环B"},admin);
  const pb=await app.publish(cycleB.id,{expectedVersion:1},admin);
  await app.move(cycleB.id,{spaceId:space.id,parentId:null,expectedVersion:pb.version},admin);
  const cycleMove=await app.move(cycleA.id,{spaceId:space.id,parentId:cycleB.id,expectedVersion:pa.version},admin);
  await assert.rejects(()=>app.publish(cycleA.id,{expectedVersion:cycleMove.version},admin),/循环/);
  check("partial cross-Space legacy publication/purge cannot bypass ancestor ACL; prospective published-parent cycles are rejected");
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),"knowledge-folder-model-")),files=new KnowledgeFilesService(app,new KnowledgePreviewJobs(ds),storage),imports=new KnowledgeImportService(app,storage);
  const docx=await createKnowledgeDocxFixture();
  const disk=async(name:string,bytes:Buffer)=>{const filename=path.join(temp,uuidv7());await fs.writeFile(filename,bytes);return {path:filename,originalname:name,size:bytes.length} as Express.Multer.File;};
  try {
    const foreign=await create("跨空间目标",undefined,other.id);
    for(const [filename,bytes] of [["员工考勤制度.docx",docx],["请假管理办法.pdf",Buffer.from("%PDF-1.7\nfixture\n%%EOF")]] as const) {
      const input={spaceId:space.id,folderId:c.id,title:filename.replace(/\.[^.]+$/,""),idempotencyKey:uuidv7()},file=await disk(filename,bytes);
      const created=await files.create(input,file,admin),replayed=await files.create(input,file,admin);
      assert.equal(replayed.id,created.id);assert.equal(replayed.repeated,true);
      await assert.rejects(()=>files.create({...input,folderId:empty.id},file,admin),/不一致/);
      const v1=await app.publish(created.id,{expectedVersion:1},admin);
      assert.equal((await query.detail(created.id,{},viewer)).folderId,c.id);
      const previouslyPublished=(await query.tree(other.id,{folderId:foreign.id},viewer)).total;
      const move=await app.move(created.id,{spaceId:other.id,folderId:foreign.id,parentId:null,expectedVersion:v1.version},admin);
      assert.equal((await query.detail(created.id,{},viewer)).spaceId,space.id);
      assert.equal((await query.tree(other.id,{folderId:foreign.id},viewer)).total,previouslyPublished);
      await app.publish(created.id,{expectedVersion:move.version},admin);
      const latest=await query.detail(created.id,{},viewer),old=await query.detail(created.id,{versionId:v1.publishedVersionId},viewer);
      assert.equal(latest.spaceId,other.id);assert.equal(latest.primaryFile!.id,old.primaryFile!.id);assert.equal(old.folderId,c.id);assert.equal(old.spaceId,space.id);
      assert.equal((await query.attachment(old.primaryFile!.id,{versionId:v1.publishedVersionId},viewer)).originalName,filename);
    }
    check("Word/PDF uploads freeze folderId in idempotent hash; replay after response loss cannot duplicate; cross-Space file moves retain originals/V1/V2");
    const preview=await imports.preview({originalname:"导入.docx",buffer:docx,size:docx.length} as Express.Multer.File,admin);
    const imported=await imports.commit({token:preview.token,spaceId:space.id,folderId:empty.id,title:"DOCX在线文章"},admin);
    const row=await query.detail(imported.id,{mode:"working"},admin);
    assert.equal(row.folderId,empty.id);assert.equal(row.contentMode,"RICH_TEXT");assert(row.contentText.includes("DOCX导入正文"));assert(row.attachments.length>0);
    check("DOCX conversion uses the same folderId command and retains embedded image attachments");
  } finally {imports.onModuleDestroy();await fs.rm(temp,{recursive:true,force:true});}
  await assert.rejects(()=>folders.delete(c.id,{expectedVersion:1},admin),/知识内容/);
  const removable=await create("可删除空目录");await folders.delete(removable.id,{expectedVersion:1},admin);
  assert.equal((await folders.list(space.id,{selectedId:removable.id},viewer)).total,0);
  check("only empty folders can be removed; tombstone retains historical references and audit rather than cascading knowledge deletion");
  const otherTenant={...admin,tenantId:"KNOWLEDGE_FOLDER_OTHER_TENANT"};
  await assert.rejects(()=>folders.list(space.id,{},otherTenant));
  await assert.rejects(()=>folders.update(c.id,{name:"跨租户",expectedVersion:1},otherTenant));
  const role="knowledge_folder_rls_"+uuidv7().replace(/-/g,"");
  await ds.query(`CREATE ROLE ${role} NOLOGIN; GRANT USAGE ON SCHEMA public TO ${role}; GRANT SELECT,INSERT ON knowledge_folders TO ${role}`);
  try { await ds.transaction(async m=>{await m.query(`SET LOCAL ROLE ${role}`);await m.query("SELECT set_config('app.tenant_id',$1,true)",[otherTenant.tenantId]);assert.equal((await m.query("SELECT id FROM knowledge_folders")).length,0);});
    await assert.rejects(()=>ds.transaction(async m=>{await m.query(`SET LOCAL ROLE ${role}`);await m.query("SELECT set_config('app.tenant_id',$1,true)",[otherTenant.tenantId]);await m.query("INSERT INTO knowledge_folders(tenant_id,space_id,name) VALUES($1,$2,'RLS denied')",[admin.tenantId,space.id]);}));
  } finally {await ds.query(`DROP OWNED BY ${role}; DROP ROLE ${role}`);}
  const [{count}]=await ds.query("SELECT count(*)::int count FROM audit_logs WHERE tenant_id=$1 AND resource='knowledge-folders'",[admin.tenantId]);assert(count>145);
  check("folder tenant isolation, genuine non-owner PostgreSQL RLS WITH CHECK and audited application writes pass without employee grant changes");
}
